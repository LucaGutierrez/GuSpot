export const DEMO_DRIVER_NAME = "Conductor Demo";

export function getSpace(id: string): Space | undefined {
  return spaces.find((s) => s.id === id);
}

export function publishedSpaces(): Space[] {
  return spaces.filter((s) => s.status === "publicado");
}

export function cities(): { city: string; neighborhoods: string[] }[] {
  const map = new Map<string, Set<string>>();
  for (const s of publishedSpaces()) {
    if (!map.has(s.city)) map.set(s.city, new Set());
    map.get(s.city)!.add(s.neighborhood);
  }
  return [...map].map(([city, n]) => ({ city, neighborhoods: [...n].sort() }));
}
